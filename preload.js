const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('aredl', {
  platform: process.platform,
  getAppVersion: () => ipcRenderer.invoke('app:version'),
  checkForUpdates: () => ipcRenderer.invoke('update:check'),
  getLevels: () => ipcRenderer.invoke('api:getLevels'),
  getChangelog: (page) => ipcRenderer.invoke('api:getChangelog', page),
  getLeaderboard: (page) => ipcRenderer.invoke('api:getLeaderboard', page),
  getProfile: (id) => ipcRenderer.invoke('api:getProfile', id),
  getLevelDetail: (levelId) => ipcRenderer.invoke('api:getLevelDetail', levelId),
  getLevelHistory: (levelId) => ipcRenderer.invoke('api:getLevelHistory', levelId),
  getLevelRecords: (levelId) => ipcRenderer.invoke('api:getLevelRecords', levelId),
  getLevelRecordsPage: (levelId, page) => ipcRenderer.invoke('api:getLevelRecordsPage', levelId, page),
  getSubmissionQueue: (submissionId) => ipcRenderer.invoke('api:getSubmissionQueue', submissionId),
  getRequestLog: () => ipcRenderer.invoke('api:getRequestLog'),
  getSubmissions: () => ipcRenderer.invoke('api:getSubmissions'),
  getMyProfile: () => ipcRenderer.invoke('api:getMyProfile'),
  onFullscreenChange: (cb) => ipcRenderer.on('window:fullscreen', (_e, on) => cb(!!on)),
  getStore: (name) => ipcRenderer.invoke('store:get', name),
  setStore: (name, data) => ipcRenderer.invoke('store:set', name, data),
  onNavCmd: (cb) => ipcRenderer.on('nav:cmd', (_e, dir) => cb(dir)),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  setTitleBarOverlay: (colors) => ipcRenderer.invoke('window:setOverlay', colors),
  getFavourites: () => ipcRenderer.invoke('favourites:get'),
  setFavourites: (list) => ipcRenderer.invoke('favourites:set', list),
  getClearedNotifications: () => ipcRenderer.invoke('notifications:getCleared'),
  setClearedNotifications: (ids) => ipcRenderer.invoke('notifications:setCleared', ids),
  getNotifications: () => ipcRenderer.invoke('api:getNotifications'),

  authStatus: () => ipcRenderer.invoke('auth:getStatus'),
  signIn: (key) => ipcRenderer.invoke('auth:setKey', key),
  signOut: () => ipcRenderer.invoke('auth:clear'),
  setMyId: (id) => ipcRenderer.invoke('auth:setMyId', id),

  onNavigate: (cb) => ipcRenderer.on('navigate', (_e, tab) => cb(tab)),
  onNewNotifications: (cb) => ipcRenderer.on('notifications:new', (_e, items) => cb(items)),
  onNewRequestLog: (cb) => ipcRenderer.on('requestLog:new', (_e, entry) => cb(entry)),
});
